func TestKyselyCodegenIsGenerated(t *testing.T) {
	// Arrange
	withHeader := "/**\n * This file was generated by kysely-codegen.\n * Please do not edit it manually.\n */\n\nexport type Account = { id: string };\n"
	withoutHeader := "import type { ColumnType } from 'kysely';\nexport type Generated<T> = T extends ColumnType<infer S, infer I, infer U>\n  ? ColumnType<S, I | undefined, U>\n  : ColumnType<T, T | undefined, T>;\n"

	// Act and assert
	for _, full := range []string{withHeader, withoutHeader} {
		c := transcript.Change{FilePath: "libs/backend/repository/src/db/types.ts", AddedText: "  reasonCode: string | null;", FullContent: full}
		if reason, _ := exclusionReason(c, false); reason != "generated" {
			t.Errorf("got %q, want generated", reason)
		}
	}
	// A diff hunk without the full file carries no marker: review it.
	if inert(transcript.Change{FilePath: "libs/backend/repository/src/db/types.ts", AddedText: "  reasonCode: string | null;"}) {
		t.Error("db/types.ts without full content must stay reviewable")
	}
	// A hand-written file that merely imports kysely stays reviewable.
	hand := "import { Kysely, sql } from 'kysely';\nexport const q = (db, id) => sql`select * from t where id = ${id}`.execute(db);\n"
	if inert(transcript.Change{FilePath: "src/repo.ts", AddedText: hand, FullContent: hand}) {
		t.Error("a hand-written kysely query file must stay reviewable")
	}
}

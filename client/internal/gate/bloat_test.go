func TestPackageBuildLayoutsAreVendored(t *testing.T) {
	// Arrange
	code := "export function render(html) { el.innerHTML = html }"

	// Act and assert
	for _, path := range []string{
		"apps/mobile/rider-app/.qa-web/react-dom/cjs/react-dom-client.production.js",
		"tra-4181/apps/mobile/rider-app/.qa-web/react-dom/cjs/react-dom-server.node.development.js",
		"public/lib/umd/widget.js",
	} {
		if reason, _ := exclusionReason(transcript.Change{FilePath: path, AddedText: code, FullContent: code}, false); reason != "vendored" {
			t.Errorf("%s: got %q, want vendored", path, reason)
		}
	}
	if inert(transcript.Change{FilePath: "/home/me/cjs/proj/src/app.js", AddedText: code}) {
		t.Error("an absolute path with a cjs/ ancestor must stay reviewable (gitless fallback)")
	}
}


func TestNodeModulesExcludedBeforeCollectingContext(
	t *testing.T,
) {
	for _, tracked := range []bool{false, true} {
		name := "untracked"
		if tracked {
			name = "tracked"
		}
		t.Run(name, func(t *testing.T) {
			dir, session := initRepo(t)
			paths := []string{"node_modules/pkg/a.js", "node_modules/pkg/b.js", "packages/web/node_modules/pkg/c.js"}
			write := func(path, body string) {
				t.Helper()
				full := filepath.Join(dir, path)
				if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			if tracked {
				for _, p := range paths {
					write(p, "module.exports = 0;\n")
				}
				gitRun(t, dir, "add", "node_modules", "packages")
				gitRun(t, dir, "commit", "-qm", "dependencies")
			}
			if err := CaptureBaseline(dir, session); err != nil {
				t.Fatal(err)
			}
			for _, p := range paths {
				write(p, strings.Repeat("module.exports = 1;\n", limits.MaxChangedFileBytes/len("module.exports = 1;\n")+1))
			}
			body := strings.Repeat("fetch(userURL);\n", 4096)
			write("src/node_modules_helper.js", body)
			got, ok, skip, err := ChangedFiles(dir, session)
			if err != nil || !ok {
				t.Fatalf("ChangedFiles: ok=%v skip=%v err=%v", ok, skip, err)
			}
			if len(got) != 1 {
				t.Fatalf("got %d changes, want only first-party source", len(got))
			}
			if got[0].FilePath != "src/node_modules_helper.js" || got[0].FullContent != body {
				t.Fatalf("first-party context lost: %+v", got[0])
			}
		})
	}
}

func TestUntrackedSnapshotExcludesNodeModules(
	t *testing.T,
) {
	dir, _ := initRepo(t)
	for _, p := range []string{"node_modules/pkg/index.js", "packages/web/node_modules/pkg/index.js", "src/node_modules_helper.js"} {
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte("fetch(url);\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, cwd := range []string{dir, filepath.Join(dir, "packages/web")} {
		got := snapshotUntracked(cwd)
		if strings.Contains(got, "node_modules/") {
			t.Fatalf("snapshot includes dependency files: %s", got)
		}
		if cwd == dir && !strings.Contains(got, "src/node_modules_helper.js") {
			t.Fatalf("snapshot lost first-party source: %s", got)
		}
	}
}

func TestRenameOutOfNodeModulesPreservesAddedLines(
	t *testing.T,
) {
	dir, session := initRepo(t)
	dependency := filepath.Join(dir, "node_modules/pkg")
	if err := os.MkdirAll(dependency, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dependency, "index.js"), []byte("fetch(userURL);\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	gitRun(t, dir, "add", "node_modules")
	gitRun(t, dir, "commit", "-qm", "dependency")
	if err := CaptureBaseline(dir, session); err != nil {
		t.Fatal(err)
	}
	gitRun(t, dir, "mv", "node_modules/pkg/index.js", "app.js")
	got, ok, skip, err := ChangedFiles(dir, session)
	if err != nil || !ok || len(got) != 1 {
		t.Fatalf("ChangedFiles: count=%d ok=%v skip=%v err=%v", len(got), ok, skip, err)
	}
	if got[0].FilePath != "app.js" || got[0].AddedText != "" || len(got[0].AddedLines) != 0 {
		t.Fatalf("renamed dependency must not be treated as newly written code: %+v", got[0])
	}
}
